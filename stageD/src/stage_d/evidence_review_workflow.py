"""Human-controlled review actions, filtered assignments, and coverage views.

The pinned Stage B queue remains an immutable machine-triage snapshot. Human
actions are stored separately in an append-only hash-chained JSONL file; no
action is generated by queue construction or automatic polarity classification.
"""
