"""Human-controlled review actions, filtered assignments, and coverage views.

The pinned Stage B queue remains an immutable machine-triage snapshot. Human
actions are stored separately in an append-only hash-chained JSONL file; no
action is generated by queue construction or automatic polarity classification.
"""
from __future__ import annotations

import argparse
import csv
import hashlib
import json
import os
import uuid
from collections import Counter
from collections.abc import Mapping, Sequence
from datetime import date
from pathlib import Path
from typing import Any

from .evidence_queue import project_root, stable_review_id, validate_review_queue


ACTION_SCHEMA_VERSION = "1.0.0"
REVIEW_STATES = {
    "SOURCE_VERIFIED", "IDENTITY_PENDING", "CONTEXT_PENDING", "CONFLICT_REVIEW",
    "READY_FOR_EXPERT_REVIEW", "EXPERT_ACCEPTED", "EXPERT_REJECTED",
}
_TERMINAL_STATES = {"EXPERT_ACCEPTED", "EXPERT_REJECTED"}
_NEGATIVE_ASSESSMENTS = {"NOT_ASSESSED", "EXPLICIT_NEGATIVE_REVIEWED", "NOT_NEGATIVE", "CONFLICTING", "UNCLEAR"}
_ZERO_HASH = "0" * 64
_EVENT_FIELDS = {
    "schema_version", "sequence", "action_id", "review_id", "evidence_id", "resulting_status",
    "reviewer_name", "reviewer_role", "review_date", "source_locator", "rationale",
    "negative_evidence_assessment", "previous_event_sha256", "event_sha256",
}


class ReviewWorkflowError(ValueError):
    """A reviewer action, assignment, or audit-log invariant is invalid."""


def _canonical(value: Any) -> bytes:
    return json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":"), allow_nan=False).encode("utf-8")


def _unique_object(pairs: list[tuple[str, Any]]) -> dict[str, Any]:
    result: dict[str, Any] = {}
    for key, value in pairs:
        if key in result:
            raise ReviewWorkflowError(f"Duplicate JSON key in audit event: {key}")
        result[key] = value
    return result


def _event_hash(event: Mapping[str, Any]) -> str:
    payload = dict(event)
    payload.pop("event_sha256", None)
    return hashlib.sha256(_canonical(payload)).hexdigest()


def _record_maps(queue: dict[str, Any]) -> tuple[dict[str, dict[str, Any]], dict[str, dict[str, Any]]]:
    validate_review_queue(queue)
    by_review = {row["review_id"]: row for row in queue["records"]}
    by_evidence = {row["source_reference"]["evidence_id"]: row for row in queue["records"]}
    return by_review, by_evidence


def _safe_audit_path(path: str | Path) -> Path:
    """Constrain audit reads/writes to Stage D and reject symlink traversal."""
    stage_d_root = (project_root() / "stageD").resolve(strict=True)
    candidate = Path(path)
    if not candidate.is_absolute():
        candidate = stage_d_root / candidate
    candidate = Path(os.path.abspath(candidate))
    try:
        relative = candidate.relative_to(stage_d_root)
    except ValueError:
        raise ReviewWorkflowError("Audit logs must stay inside the Stage D workspace") from None
    cursor = stage_d_root
    for part in relative.parts:
        cursor = cursor / part
        if cursor.is_symlink():
            raise ReviewWorkflowError("Audit log paths cannot traverse symbolic links")
    try:
        candidate.resolve(strict=False).relative_to(stage_d_root)
    except ValueError:
        raise ReviewWorkflowError("Audit log resolves outside Stage D") from None
    if candidate.exists() and not candidate.is_file():
        raise ReviewWorkflowError("Audit log path must be a regular file")
    return candidate


def _check_action_fields(action: Mapping[str, Any], queue_record: Mapping[str, Any], previous_state: str) -> None:
    required = ("resulting_status", "reviewer_name", "reviewer_role", "review_date", "source_locator", "rationale")
    missing = [key for key in required if not isinstance(action.get(key), str) or not action[key].strip()]
    if missing:
        raise ReviewWorkflowError("Reviewer action is missing required fields: " + ", ".join(missing))
    if action.get("schema_version") not in {None, ACTION_SCHEMA_VERSION}:
        raise ReviewWorkflowError("Unsupported reviewer-action schema version")
    status = action["resulting_status"]
    if not isinstance(status, str) or status not in REVIEW_STATES:
        raise ReviewWorkflowError(f"Unsupported human review status: {status}")
    try:
        date.fromisoformat(action["review_date"])
    except ValueError:
        raise ReviewWorkflowError("review_date must be an ISO date") from None
    if status == "READY_FOR_EXPERT_REVIEW" and previous_state != "SOURCE_VERIFIED":
        raise ReviewWorkflowError("READY_FOR_EXPERT_REVIEW requires a prior SOURCE_VERIFIED reviewer action")
    if status in _TERMINAL_STATES:
        if previous_state != "READY_FOR_EXPERT_REVIEW":
            raise ReviewWorkflowError("Expert decisions require a prior READY_FOR_EXPERT_REVIEW action")
        if action["reviewer_role"].strip() != "expert":
            raise ReviewWorkflowError("EXPERT_ACCEPTED/EXPERT_REJECTED requires reviewer_role=expert")
    if previous_state in _TERMINAL_STATES:
        raise ReviewWorkflowError("An expert decision is terminal in this workflow; correction policy is not configured")

    expected_evidence_id = queue_record["source_reference"]["evidence_id"]
    if action.get("evidence_id") not in (None, expected_evidence_id):
        raise ReviewWorkflowError("Action Evidence_ID does not match the selected queue record")
    if action.get("review_id") not in (None, queue_record["review_id"]):
        raise ReviewWorkflowError("Action review_id does not match the selected queue record")
    negative = action.get("negative_evidence_assessment", "NOT_ASSESSED")
    if not isinstance(negative, str) or negative not in _NEGATIVE_ASSESSMENTS:
        raise ReviewWorkflowError("Unsupported negative_evidence_assessment value")
    if negative == "EXPLICIT_NEGATIVE_REVIEWED" and status not in {"SOURCE_VERIFIED", "READY_FOR_EXPERT_REVIEW", "EXPERT_ACCEPTED", "EXPERT_REJECTED"}:
        raise ReviewWorkflowError("Explicit negative assessment requires a source-verified review state")


def verify_review_action_log(path: str | Path, queue: dict[str, Any]) -> list[dict[str, Any]]:
    """Read and verify append-only JSONL history, linkage, dates, transitions and hash chain."""
    by_review, by_evidence = _record_maps(queue)
    log_path = _safe_audit_path(path)
    if not log_path.exists():
        return []
    raw_bytes = log_path.read_bytes()
    if not raw_bytes:
        return []
    if not raw_bytes.endswith(b"\n"):
        raise ReviewWorkflowError("Audit log is truncated: the final event has no newline terminator")
    try:
        lines = raw_bytes.decode("utf-8").splitlines()
    except UnicodeDecodeError:
        raise ReviewWorkflowError("Audit log must be UTF-8 JSONL") from None

    events: list[dict[str, Any]] = []
    seen_actions: set[str] = set()
    latest_state: dict[str, str] = {}
    previous_hash = _ZERO_HASH
    for line_number, line in enumerate(lines, start=1):
        if not line.strip():
            raise ReviewWorkflowError(f"Blank line in audit log at line {line_number}")
        try:
            event = json.loads(line, object_pairs_hook=_unique_object)
        except (json.JSONDecodeError, ReviewWorkflowError) as exc:
            detail = exc.msg if isinstance(exc, json.JSONDecodeError) else str(exc)
            raise ReviewWorkflowError(f"Malformed audit event at line {line_number}: {detail}") from None
        if not isinstance(event, dict) or event.get("schema_version") != ACTION_SCHEMA_VERSION:
            raise ReviewWorkflowError(f"Unsupported audit event at line {line_number}")
        if set(event) != _EVENT_FIELDS:
            raise ReviewWorkflowError(f"Audit event has unexpected or missing fields at line {line_number}")
        if event.get("sequence") != line_number:
            raise ReviewWorkflowError(f"Audit sequence is not contiguous at line {line_number}")
        action_id = event.get("action_id")
        if not isinstance(action_id, str) or not action_id or action_id in seen_actions:
            raise ReviewWorkflowError(f"Missing or duplicate action_id at line {line_number}")
        seen_actions.add(action_id)
        if event.get("previous_event_sha256") != previous_hash:
            raise ReviewWorkflowError(f"Audit hash-chain link is invalid at line {line_number}")
        if event.get("event_sha256") != _event_hash(event):
            raise ReviewWorkflowError(f"Audit event hash is invalid at line {line_number}")
        review_id, evidence_id = event.get("review_id"), event.get("evidence_id")
        if not isinstance(review_id, str) or not isinstance(evidence_id, str) or review_id not in by_review or evidence_id not in by_evidence or by_review[review_id] is not by_evidence[evidence_id]:
            raise ReviewWorkflowError(f"Audit event refers to a non-matching queue record at line {line_number}")
        before = latest_state.get(review_id, "NOT_REVIEWED")
        _check_action_fields(event, by_review[review_id], before)
        latest_state[review_id] = event["resulting_status"]
        previous_hash = event["event_sha256"]
        events.append(event)
    return events


def validate_review_events(queue: dict[str, Any], events: Sequence[Mapping[str, Any]]) -> None:
    """Validate caller-supplied action events before using them as review state."""
    by_review, by_evidence = _record_maps(queue)
    previous_hash = _ZERO_HASH
    states: dict[str, str] = {}
    action_ids: set[str] = set()
    for index, supplied in enumerate(events, start=1):
        if not isinstance(supplied, Mapping):
            raise ReviewWorkflowError(f"Audit event {index} must be an object")
        event = dict(supplied)
        if event.get("schema_version") != ACTION_SCHEMA_VERSION or event.get("sequence") != index:
            raise ReviewWorkflowError(f"Audit event {index} has an invalid version or sequence")
        if set(event) != _EVENT_FIELDS:
            raise ReviewWorkflowError(f"Audit event {index} has unexpected or missing fields")
        action_id, review_id, evidence_id = event.get("action_id"), event.get("review_id"), event.get("evidence_id")
        if not isinstance(action_id, str) or not action_id or action_id in action_ids:
            raise ReviewWorkflowError(f"Audit event {index} has a missing or duplicate action_id")
        action_ids.add(action_id)
        if not isinstance(review_id, str) or not isinstance(evidence_id, str) or review_id not in by_review or evidence_id not in by_evidence or by_review[review_id] is not by_evidence[evidence_id]:
            raise ReviewWorkflowError(f"Audit event {index} does not match a queue record")
        if event.get("previous_event_sha256") != previous_hash or event.get("event_sha256") != _event_hash(event):
            raise ReviewWorkflowError(f"Audit event {index} breaks the hash chain")
        _check_action_fields(event, by_review[review_id], states.get(review_id, "NOT_REVIEWED"))
        states[review_id] = event["resulting_status"]
        previous_hash = event["event_sha256"]


def append_review_action(path: str | Path, queue: dict[str, Any], action: Mapping[str, Any]) -> dict[str, Any]:
    """Append one explicitly supplied reviewer action; never edits the source queue."""
    by_review, by_evidence = _record_maps(queue)
    review_id = action.get("review_id")
    evidence_id = action.get("evidence_id")
    record = by_review.get(review_id) if isinstance(review_id, str) else None
    if record is None or (isinstance(evidence_id, str) and by_evidence.get(evidence_id) is not record):
        raise ReviewWorkflowError("A matching stable review_id and Evidence_ID are required")
    log_path = _safe_audit_path(path)
    events = verify_review_action_log(log_path, queue)
    latest = {event["review_id"]: event["resulting_status"] for event in events}
    previous_state = latest.get(review_id, "NOT_REVIEWED")
    _check_action_fields(action, record, previous_state)
    action_id = action.get("action_id") or str(uuid.uuid4())
    if not isinstance(action_id, str) or not action_id:
        raise ReviewWorkflowError("action_id must be a nonempty string")
    if any(event["action_id"] == action_id for event in events):
        raise ReviewWorkflowError("action_id already exists in audit history")
    previous_hash = events[-1]["event_sha256"] if events else _ZERO_HASH
    event = {
        "schema_version": ACTION_SCHEMA_VERSION,
        "sequence": len(events) + 1,
        "action_id": action_id,
        "review_id": record["review_id"],
        "evidence_id": record["source_reference"]["evidence_id"],
        "resulting_status": action["resulting_status"],
        "reviewer_name": action["reviewer_name"].strip(),
        "reviewer_role": action["reviewer_role"].strip(),
        "review_date": action["review_date"],
        "source_locator": action["source_locator"].strip(),
        "rationale": action["rationale"].strip(),
        "negative_evidence_assessment": action.get("negative_evidence_assessment", "NOT_ASSESSED"),
        "previous_event_sha256": previous_hash,
    }
    event["event_sha256"] = _event_hash(event)
    log_path.parent.mkdir(parents=True, exist_ok=True)
    with log_path.open("ab") as stream:
        stream.write(_canonical(event) + b"\n")
        stream.flush()
        os.fsync(stream.fileno())
    return event


def _latest_states(queue: dict[str, Any], events: Sequence[Mapping[str, Any]]) -> dict[str, str]:
    latest = {row["review_id"]: "NOT_REVIEWED" for row in queue["records"]}
    for event in events:
        latest[event["review_id"]] = event["resulting_status"]
    return latest


def _contains(needle: Any, *haystacks: Any) -> bool:
    if needle is None or str(needle).strip() == "":
        return True
    target = str(needle).strip().casefold()
    return any(target in str(value or "").casefold() for value in haystacks)


def filter_review_queue(
    queue: dict[str, Any],
    *,
    events: Sequence[Mapping[str, Any]] = (),
    compound: str | None = None,
    drug: str | None = None,
    study: str | None = None,
    evidence_category: str | None = None,
    outcome_polarity: str | None = None,
    conflict_status: str | None = None,
    identity_status: str | None = None,
    source_verification_status: str | None = None,
    human_review_status: str | None = None,
) -> list[dict[str, Any]]:
    """Return records matching source labels and separately recorded review history."""
    validate_review_queue(queue)
    validate_review_events(queue, events)
    states = _latest_states(queue, events)
    verified_ids = {
        event["review_id"] for event in events
        if event.get("resulting_status") in {"SOURCE_VERIFIED", "READY_FOR_EXPERT_REVIEW", "EXPERT_ACCEPTED", "EXPERT_REJECTED"}
    }
    result: list[dict[str, Any]] = []
    for record in queue["records"]:
        source = record["source_record"]
        machine = record["machine_assessment"]
        state = states[record["review_id"]]
        has_conflict = bool(source.get("Conflict_Group")) or machine.get("triage_state") == "CONFLICT_REVIEW"
        if not _contains(compound, source.get("Compound_ID"), source.get("Compound")):
            continue
        if not _contains(drug, source.get("Drug"), source.get("Perpetrator")):
            continue
        if not _contains(study, source.get("Study_ID"), source.get("Source_Title"), source.get("PMID"), source.get("DOI")):
            continue
        if not _contains(evidence_category, source.get("Evidence_Type"), machine.get("normalized_study_category")):
            continue
        if not _contains(outcome_polarity, machine.get("finding_polarity")):
            continue
        conflict = str(conflict_status or "").strip().casefold()
        if conflict in {"conflict", "conflict_review", "yes", "true"} and not has_conflict:
            continue
        if conflict in {"no_conflict", "none", "no", "false"} and has_conflict:
            continue
        if conflict and conflict not in {"conflict", "conflict_review", "yes", "true", "no_conflict", "none", "no", "false"} and not _contains(conflict_status, source.get("Conflict_Group")):
            continue
        identity_value = source.get("Identity_Status")
        if state == "IDENTITY_PENDING":
            identity_value = f"{identity_value} IDENTITY_PENDING"
        if not _contains(identity_status, identity_value):
            continue
        verified_status = "SOURCE_VERIFIED" if record["review_id"] in verified_ids else "NOT_PERFORMED"
        if not _contains(source_verification_status, verified_status):
            continue
        if not _contains(human_review_status, state):
            continue
        result.append(record)
    return result


def build_assignment_export(
    queue: dict[str, Any],
    *,
    events: Sequence[Mapping[str, Any]] = (),
    filters: Mapping[str, Any] | None = None,
    assigned_to: str | None = None,
) -> dict[str, Any]:
    filters = dict(filters or {})
    selected = filter_review_queue(queue, events=events, **filters)
    records = []
    states = _latest_states(queue, events)
    verified_ids = {
        event["review_id"] for event in events
        if event.get("resulting_status") in {"SOURCE_VERIFIED", "READY_FOR_EXPERT_REVIEW", "EXPERT_ACCEPTED", "EXPERT_REJECTED"}
    }
    for record in selected:
        source = record["source_record"]
        records.append({
            "review_id": record["review_id"],
            "evidence_id": record["source_reference"]["evidence_id"],
            "compound_id": source.get("Compound_ID", ""),
            "compound_source_label": source.get("Compound", ""),
            "drug_source_label": source.get("Drug", ""),
            "study_id": source.get("Study_ID", ""),
            "source_title": source.get("Source_Title", ""),
            "evidence_category": source.get("Evidence_Type", ""),
            "outcome_polarity_machine_triage": record["machine_assessment"]["finding_polarity"],
            "machine_triage_state": record["machine_assessment"]["triage_state"],
            "identity_source_label": source.get("Identity_Status", ""),
            "source_verification_status": "SOURCE_VERIFIED" if record["review_id"] in verified_ids else "NOT_PERFORMED",
            "conflict_group": source.get("Conflict_Group", ""),
            "source_url": source.get("Source_URL", ""),
            "doi": source.get("DOI", ""),
            "pmid": source.get("PMID", ""),
            "source_locator": source.get("Source_Locator", ""),
            "review_status": states[record["review_id"]],
        })
    assignment_id = "ASG-" + hashlib.sha256(_canonical({
        "source_sha256": queue["source"]["sha256"],
        "review_ids": [record["review_id"] for record in selected],
        "filters": filters,
        "assigned_to": assigned_to,
    })).hexdigest()[:16].upper()
    return {
        "schema_version": "1.0.0",
        "assignment_id": assignment_id,
        "source_release_id": queue["source"]["release_id"],
        "source_sha256": queue["source"]["sha256"],
        "assigned_to": assigned_to,
        "filters": filters,
        "record_count": len(records),
        "purpose_and_limits": {
            "assignment_is_human_review": False,
            "decisions_created": False,
            "negative_inference_created": False,
            "note": "Exporting or assigning rows records no source review or expert decision.",
        },
        "records": records,
    }


def build_coverage_dashboard(queue: dict[str, Any], events: Sequence[Mapping[str, Any]] = ()) -> dict[str, Any]:
    validate_review_queue(queue)
    validate_review_events(queue, events)
    latest = _latest_states(queue, events)
    human_counts = Counter(latest.values())
    verified_ids = {
        event["review_id"] for event in events
        if event.get("resulting_status") in {"SOURCE_VERIFIED", "READY_FOR_EXPERT_REVIEW", "EXPERT_ACCEPTED", "EXPERT_REJECTED"}
    }
    polarity = Counter(record["machine_assessment"]["finding_polarity"] for record in queue["records"])
    machine = Counter(record["machine_assessment"]["triage_state"] for record in queue["records"])
    record_count = len(queue["records"])
    reviewed_count = sum(count for state, count in human_counts.items() if state != "NOT_REVIEWED")
    return {
        "schema_version": "1.0.0",
        "source_release_id": queue["source"]["release_id"],
        "source_sha256": queue["source"]["sha256"],
        "record_count": record_count,
        "machine_triage_counts": dict(sorted(machine.items())),
        "human_review_status_counts": dict(sorted(human_counts.items())),
        "source_verification_status_counts": {
            "SOURCE_VERIFIED": len(verified_ids),
            "NOT_PERFORMED": record_count - len(verified_ids),
        },
        "machine_source_polarity_counts": dict(sorted(polarity.items())),
        "reviewed_record_count": reviewed_count,
        "not_reviewed_record_count": human_counts.get("NOT_REVIEWED", 0),
        "review_coverage_fraction": reviewed_count / record_count if record_count else 0.0,
        "audit_action_count": len(events),
        "expert_accepted_count": human_counts.get("EXPERT_ACCEPTED", 0),
        "expert_rejected_count": human_counts.get("EXPERT_REJECTED", 0),
        "automatic_approval_count": 0,
        "automatic_negative_inference_count": 0,
        "negative_assessments_require_human_action": True,
    }


def export_assignment_json(path: str | Path, assignment: Mapping[str, Any]) -> None:
    destination = Path(path)
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(json.dumps(assignment, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def export_assignment_csv(path: str | Path, assignment: Mapping[str, Any]) -> None:
    rows = assignment.get("records", [])
    columns = [
        "assignment_id", "source_release_id", "source_sha256", "assigned_to",
        "review_id", "evidence_id", "compound_id", "compound_source_label", "drug_source_label",
        "study_id", "source_title", "evidence_category", "outcome_polarity_machine_triage",
        "machine_triage_state", "identity_source_label", "source_verification_status", "conflict_group",
        "source_url", "doi", "pmid", "source_locator", "review_status",
    ]
    destination = Path(path)
    destination.parent.mkdir(parents=True, exist_ok=True)
    with destination.open("w", encoding="utf-8", newline="") as stream:
        writer = csv.DictWriter(stream, fieldnames=columns, extrasaction="ignore")
        writer.writeheader()
        provenance = {
            "assignment_id": assignment.get("assignment_id", ""),
            "source_release_id": assignment.get("source_release_id", ""),
            "source_sha256": assignment.get("source_sha256", ""),
            "assigned_to": assignment.get("assigned_to") or "",
        }
        writer.writerows({**provenance, **row} for row in rows)


def _load_queue() -> dict[str, Any]:
    path = project_root() / "stageD/data/evidence_review_queue.json"
    queue = json.loads(path.read_text(encoding="utf-8"))
    validate_review_queue(queue)
    return queue


def main() -> None:
    parser = argparse.ArgumentParser(description="Filter, export, and report on the Stage D evidence review queue")
    parser.add_argument("--compound")
    parser.add_argument("--drug")
    parser.add_argument("--study")
    parser.add_argument("--evidence-category")
    parser.add_argument("--outcome-polarity")
    parser.add_argument("--conflict-status")
    parser.add_argument("--identity-status")
    parser.add_argument("--source-verification-status")
    parser.add_argument("--human-review-status")
    parser.add_argument("--assigned-to")
    parser.add_argument("--audit-log", type=Path, default=project_root() / "stageD/data/evidence_review_actions.jsonl")
    parser.add_argument("--json-output", type=Path)
    parser.add_argument("--csv-output", type=Path)
    parser.add_argument("--coverage-output", type=Path)
    args = parser.parse_args()
    queue = _load_queue()
    events = verify_review_action_log(args.audit_log, queue)
    coverage = build_coverage_dashboard(queue, events)
    if args.coverage_output:
        args.coverage_output.parent.mkdir(parents=True, exist_ok=True)
        args.coverage_output.write_text(json.dumps(coverage, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    filters = {key: value for key, value in {
        "compound": args.compound,
        "drug": args.drug,
        "study": args.study,
        "evidence_category": args.evidence_category,
        "outcome_polarity": args.outcome_polarity,
        "conflict_status": args.conflict_status,
        "identity_status": args.identity_status,
        "source_verification_status": args.source_verification_status,
        "human_review_status": args.human_review_status,
    }.items() if value is not None}
    if args.json_output or args.csv_output:
        assignment = build_assignment_export(queue, events=events, filters=filters, assigned_to=args.assigned_to)
        if args.json_output:
            export_assignment_json(args.json_output, assignment)
        if args.csv_output:
            export_assignment_csv(args.csv_output, assignment)
        print(json.dumps({"assignment_id": assignment["assignment_id"], "record_count": assignment["record_count"], "coverage": coverage}, indent=2))
    else:
        print(json.dumps(coverage, indent=2, sort_keys=True))


if __name__ == "__main__":
    main()
